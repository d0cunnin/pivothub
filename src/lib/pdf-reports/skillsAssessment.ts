import type jsPDF from 'jspdf';
import { PdfWriter, asText, toList, ACCENT, CON, HEADING, PRO } from '../pdfWriter';
import { actionPlan, scoreBar, table, toNumber } from './scoreReportBlocks';

export interface SkillAreaResult {
  name: string;
  /** Correct answers out of 10. */
  score: number;
  level: string;
}

const levelColor = (level: string) =>
  /strong/i.test(level) ? PRO : /moderate/i.test(level) ? ACCENT : CON;

/**
 * Builds the Skills Assessment PDF from the per-area scores and the AI
 * analysis returned by enhanced-assessment-analyzer (assessmentType "skills").
 */
export function generateSkillsAssessmentPDF(areas: SkillAreaResult[], ai: any): jsPDF {
  const w = new PdfWriter();
  w.header('Skills Assessment Results', 'A snapshot of your current skills and how to grow them');

  const sorted = [...areas].sort((a, b) => b.score - a.score);
  const top = sorted.slice(0, 3);
  if (top.length) {
    w.section('Your Top 3 Skill Areas');
    top.forEach((area, index) => {
      w.ensureSpace(12);
      w.badge(`#${index + 1}`, 14);
      w.setStyle(12, HEADING, 'bold');
      w.doc.text(asText(area.name), w.margin + 19, w.y);
      w.setStyle(10, levelColor(area.level));
      w.doc.text(`${area.score}/10  -  ${asText(area.level)}`, w.pageWidth - w.margin, w.y, { align: 'right' });
      w.y += 10;
    });
    w.y += 2;
  }

  const readiness = toNumber(ai?.readinessScore);
  const summary = asText(ai?.summary);
  const overall = toNumber(ai?.overallScore);
  if (readiness !== null || summary || overall !== null) {
    w.section(readiness !== null ? 'Career Readiness' : 'Your Overall Score');
    if (readiness !== null) scoreBar(w, 'Career readiness', readiness, 100, `${readiness}%`);
    if (overall !== null) scoreBar(w, 'Overall skills score', overall, 10, `${overall}/10`);
    if (summary) w.markdown(summary);
    w.y += 4;
  }

  if (sorted.length) {
    w.section('All Skill Areas', 'Correct answers out of 10 in each area');
    sorted.forEach((area) => scoreBar(w, asText(area.name), area.score, 10, `${area.score}/10  -  ${asText(area.level)}`, levelColor(area.level)));
    w.y += 2;
  }

  const topSkills = toList(ai?.topSkills);
  if (topSkills.length) {
    w.section('Skills You Can Lean On');
    w.bullets(topSkills);
    w.y += 4;
  }

  const gaps = toList(ai?.skillGaps);
  if (gaps.length) {
    w.section('Skills Worth Building');
    w.bullets(gaps);
    w.y += 4;
  }

  const categories: any[] = Array.isArray(ai?.skillCategories) ? ai.skillCategories : [];
  if (categories.length) {
    w.section('Skill Area Details');
    categories.forEach((cat, i) => {
      const score = toNumber(cat?.score);
      const level = asText(cat?.level);
      const valueText = [score !== null ? `${score}/10` : '', level].filter(Boolean).join('  -  ');
      if (score !== null) scoreBar(w, asText(cat?.category), score, 10, valueText);
      else w.subHeading([asText(cat?.category), level].filter(Boolean).join('  -  '));
      const strengths = toList(cat?.strengths);
      if (strengths.length) {
        w.subHeading('Strengths', PRO, 10);
        w.bullets(strengths, { size: 9.5 });
      }
      const improvements = toList(cat?.improvements);
      if (improvements.length) {
        w.subHeading('To improve', CON, 10);
        w.bullets(improvements, { size: 9.5 });
      }
      if (i < categories.length - 1) w.y += 3;
    });
    w.y += 4;
  }

  actionPlan(w, ai?.actionPlan);

  const learningPath: any[] = Array.isArray(ai?.learningPath) ? ai.learningPath : [];
  if (learningPath.length) {
    w.section('Your Learning Path');
    table(
      w,
      ['Step', 'Timeframe', 'Resources'],
      learningPath.map((s) =>
        typeof s === 'object' && s
          ? [asText(s.step), asText(s.timeframe), toList(s.resources).join('\n')]
          : [asText(s), '', ''],
      ),
      { columnStyles: { 1: { cellWidth: 30 }, 2: { cellWidth: 55 } } },
    );
  }

  const impact = asText(ai?.careerImpact);
  if (impact) {
    w.section('How This Helps Your Career');
    w.markdown(impact);
    w.y += 4;
  }

  const certs = toList(ai?.certifications);
  if (certs.length) {
    w.section('Certifications to Consider');
    w.bullets(certs);
    w.y += 4;
  }

  const practice = toList(ai?.practiceOpportunities);
  if (practice.length) {
    w.section('Ways to Practice');
    w.bullets(practice);
  }

  w.footer('Generated by PivotHub');
  return w.doc;
}
