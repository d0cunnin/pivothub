import type jsPDF from 'jspdf';
import { PdfWriter, asText } from '../pdfWriter';
import { rawText, renderAiText, wrappedHeader } from './toolReportBlocks';

/** Launch It: the AI launch strategy (markdown mixed with plain-text headings). */
export function generateLaunchItPDF(ideaCategory: string, strategy: string): jsPDF {
  const w = new PdfWriter();
  wrappedHeader(w, 'Launch Strategy', asText(ideaCategory) || 'Your Project');
  renderAiText(w, rawText(strategy));
  w.footer('Generated by PivotHub');
  return w.doc;
}
