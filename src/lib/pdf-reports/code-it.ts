import type jsPDF from 'jspdf';
import { PdfWriter } from '../pdfWriter';
import { codeBlock, rawText, renderAiText } from './toolReportBlocks';

export interface CodeExplanation {
  explanation: string;
  expectedOutput: string;
  tips?: string;
}

/** Code It: the user's code with the AI explanation, expected output and tips. */
export function generateCodeItPDF(userCode: string, explanation: CodeExplanation): jsPDF {
  const w = new PdfWriter();
  w.header('Code Explanation', 'What your code does, what it prints, and how to improve it');

  const code = rawText(userCode);
  if (code.trim()) {
    w.section('Your Code');
    codeBlock(w, code);
    w.y += 3;
  }

  const text = rawText(explanation?.explanation);
  if (text) {
    w.section('What It Does');
    renderAiText(w, text, { demote: true });
    w.y += 2;
  }

  const output = rawText(explanation?.expectedOutput);
  if (output.trim()) {
    w.section('Expected Output');
    // The output is usually raw program output; strip a wrapping ``` fence if the AI added one.
    codeBlock(w, output.replace(/^\s*```[^\n]*\n?|\n?```\s*$/g, ''));
    w.y += 3;
  }

  const tips = rawText(explanation?.tips);
  if (tips) {
    w.section('Tips');
    renderAiText(w, tips, { demote: true });
  }

  w.footer('Generated by HireYourself Platform');
  return w.doc;
}
