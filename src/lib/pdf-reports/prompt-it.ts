import type jsPDF from 'jspdf';
import { PdfWriter } from '../pdfWriter';
import { quoteBlock, rawText, renderAiText } from './toolReportBlocks';

export interface PromptFeedback {
  analysis: string;
  improvedPrompt: string;
  explanation: string;
}

/** Prompt It: original prompt, expert analysis, improved prompt and why it works. */
export function generatePromptItPDF(userPrompt: string, feedback: PromptFeedback): jsPDF {
  const w = new PdfWriter();
  w.header('Prompt Analysis', 'Expert feedback on your prompt, with an improved version');

  const original = rawText(userPrompt);
  if (original.trim()) {
    w.section('Your Original Prompt');
    quoteBlock(w, original);
    w.y += 3;
  }

  const analysis = rawText(feedback?.analysis);
  if (analysis) {
    w.section('Expert Analysis');
    renderAiText(w, analysis, { demote: true });
    w.y += 2;
  }

  const improved = rawText(feedback?.improvedPrompt);
  if (improved) {
    w.section('Improved Prompt', 'Copy this into your AI tool');
    quoteBlock(w, improved);
    w.y += 3;
  }

  const why = rawText(feedback?.explanation);
  if (why) {
    w.section('Why It Works');
    renderAiText(w, why, { demote: true });
  }

  w.footer('Generated by HireYourself Platform');
  return w.doc;
}
