import type jsPDF from 'jspdf';
import { PdfWriter, asText } from '../pdfWriter';
import { note, rawText, renderAiText, wrappedHeader } from './toolReportBlocks';
import { richMarkdown } from './markdownBlocks';

/** Speak It: speaker development strategy or podcast launch plan (AI markdown). */
export function generateSpeakItPDF(path: 'speaker' | 'podcaster', fullName: string, plan: string): jsPDF {
  const w = new PdfWriter();
  const title = path === 'speaker' ? 'Speaker Development & Launch Strategy' : 'Podcast Launch Plan';
  const name = asText(fullName);
  wrappedHeader(w, title, name ? `Prepared for: ${name}` : 'Your launch plan');
  note(w, 'This file is not stored on our servers. Keep this download to save a copy.');
  if (path === 'speaker') {
    // The speaker report uses tables (content calendar, action plan), which
    // richMarkdown draws as real tables.
    const body = rawText(plan).replace(/^#\s+Speaker Development & Launch Strategy[^\n]*\n/, '');
    richMarkdown(w, body);
  } else {
    renderAiText(w, rawText(plan));
  }
  w.footer('Generated by PivotHub Speak It');
  return w.doc;
}
