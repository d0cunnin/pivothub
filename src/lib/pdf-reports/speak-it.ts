import type jsPDF from 'jspdf';
import { PdfWriter, asText } from '../pdfWriter';
import { note, rawText, renderAiText, wrappedHeader } from './toolReportBlocks';

/** Speak It: public speaking or podcast launch plan (AI markdown). */
export function generateSpeakItPDF(path: 'speaker' | 'podcaster', fullName: string, plan: string): jsPDF {
  const w = new PdfWriter();
  const title = `${path === 'speaker' ? 'Public Speaking' : 'Podcast'} Launch Plan`;
  const name = asText(fullName);
  wrappedHeader(w, title, name ? `Generated for: ${name}` : 'Your launch plan');
  note(w, 'This file is not stored on our servers. Keep this download to save a copy.');
  renderAiText(w, rawText(plan));
  w.footer('Generated by PivotHub Speak It');
  return w.doc;
}
