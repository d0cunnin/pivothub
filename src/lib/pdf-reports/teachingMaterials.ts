import type jsPDF from 'jspdf';
import { PdfWriter, asText, toList, pdfSafe } from '../pdfWriter';
import { reportHeader, renderAiText } from './reportBlocks';

export interface TeachingMaterialsProfile {
  fullName: string;
  skills: { category: string; specificSkill: string; proficiency: string }[];
  militaryService?: string;
  militaryBranch?: string;
  militaryRank?: string;
  militaryRole?: string;
  experience?: string;
  educationLevel: string;
  professionalDegreeType?: string;
  major: string;
  otherMajor?: string;
  certifications?: string;
  teachingFormat: string;
  targetAudience: string[];
  otherAudience?: string;
  duration: string;
}

export interface TeachingMaterialsContent {
  webinarConcepts: string;
  courseOutline: string;
  handouts: string;
  lessonScript: string;
  toolsAndPlatforms: string;
  marketingPlan: string;
}

const DISCLAIMER =
  'This teaching content is provided for educational and instructional purposes. PivotHub does not guarantee specific revenue or student outcomes.';

function educationText(p: TeachingMaterialsProfile): string {
  const level = asText(p.educationLevel);
  if (level === 'Professional Degree' && p.professionalDegreeType) return asText(p.professionalDegreeType);
  const major = p.major === 'Other' ? asText(p.otherMajor) : asText(p.major);
  if (level === 'Other' && !p.major) return asText(p.otherMajor);
  return [level, major ? `in ${major}` : ''].filter(Boolean).join(' ');
}

/** Builds the "Download PDF" teaching materials package from Teach It. */
export function generateTeachingMaterialsPDF(
  profile: TeachingMaterialsProfile,
  materials: TeachingMaterialsContent,
): jsPDF {
  const w = new PdfWriter();
  const name = asText(profile?.fullName);
  reportHeader(w, 'Your Teaching Materials', name ? `Course monetization package for ${name}` : 'Course monetization package');

  const skills = (Array.isArray(profile?.skills) ? profile.skills : [])
    .map((s) => {
      const skill = [asText(s?.category), asText(s?.specificSkill)].filter(Boolean).join(': ');
      const level = asText(s?.proficiency);
      return level ? `${skill} (${level})` : skill;
    })
    .filter(Boolean);
  const audience = [...toList(profile?.targetAudience).filter((a) => a !== 'Other'), asText(profile?.otherAudience)]
    .filter(Boolean)
    .join(', ') || toList(profile?.targetAudience).join(', ');
  const military =
    profile?.militaryService === 'yes'
      ? [asText(profile.militaryBranch), asText(profile.militaryRank), asText(profile.militaryRole)].filter(Boolean).join(', ') || 'Yes'
      : '';

  w.section('Instructor Profile');
  w.facts([
    ['Name', name],
    ['Skills', skills.join('; ')],
    ['Experience', asText(profile?.experience)],
    ['Education', educationText(profile)],
    ['Certifications', asText(profile?.certifications)],
    ['Military service', military],
    ['Teaching format', asText(profile?.teachingFormat)],
    ['Target audience', audience],
    ['Duration', asText(profile?.duration)],
  ]);

  const sections: [string, string, unknown][] = [
    ['Webinar and Course Concepts', 'Ideas you can turn into a paid offer', materials?.webinarConcepts],
    ['Course Outline and Modules', '', materials?.courseOutline],
    ['Handouts and Resources', 'Give these to your students', materials?.handouts],
    ['Lesson Scripts and Talking Points', '', materials?.lessonScript],
    ['Tools and Setup Guide', '', materials?.toolsAndPlatforms],
    ['Marketing Plan', 'How to find your first students', materials?.marketingPlan],
  ];
  sections.forEach(([title, subtitle, content]) => {
    const text = typeof content === 'string' ? content : asText(content);
    if (!text.trim()) return;
    // A divider between sections, unless the next one starts a fresh page anyway.
    if (w.y + 50 <= w.pageHeight - w.margin - 5) w.divider();
    else w.ensureSpace(w.pageHeight);
    w.section(title, subtitle || undefined);
    renderAiText(w, text, { titleLineHeadings: true });
  });

  // The disclaimer sits on every page, above the page number line.
  const total = w.doc.getNumberOfPages();
  for (let i = 1; i <= total; i++) {
    w.doc.setPage(i);
    w.setStyle(7.5, [156, 163, 175]);
    const lines: string[] = w.doc.splitTextToSize(pdfSafe(DISCLAIMER), w.contentWidth);
    lines.forEach((line, li) => w.doc.text(line, w.pageWidth / 2, w.pageHeight - 17 - (lines.length - 1 - li) * 3.5, { align: 'center' }));
  }
  w.footer('Teaching materials generated by PivotHub');
  return w.doc;
}
