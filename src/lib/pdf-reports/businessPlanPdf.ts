import type jsPDF from 'jspdf';
import { PdfWriter, asText } from '../pdfWriter';
import { richMarkdown } from './markdownBlocks';

const ACRONYMS = new Set([
  'AI', 'API', 'B2B', 'B2C', 'CAC', 'CRM', 'DBA', 'EIN', 'FAQ', 'KPI', 'KPIS', 'LLC', 'LTV', 'MVP',
  'P&L', 'PR', 'ROI', 'SAAS', 'SAM', 'SEO', 'SOM', 'SWOT', 'TAM', 'UK', 'US', 'USA', 'USP', 'UVP',
]);
const SMALL_WORDS = new Set(['a', 'an', 'and', 'as', 'at', 'by', 'for', 'in', 'of', 'on', 'or', 'the', 'to', 'vs', 'with']);

const fixAcronym = (w: string) => (w.toUpperCase() === 'KPIS' ? 'KPIs' : w.toUpperCase() === 'SAAS' ? 'SaaS' : w.toUpperCase());

/** "GO-TO-MARKET STRATEGY & KPIS" -> "Go-to-Market Strategy & KPIs". */
export function titleCase(s: string): string {
  return s
    .toLowerCase()
    .split(/(\s+)/)
    .map((word, i) =>
      word
        .split('-')
        .map((part, j) => {
          const bare = part.replace(/[^a-z0-9&]/gi, '');
          if (ACRONYMS.has(bare.toUpperCase())) return part.replace(bare, fixAcronym(bare));
          if ((i > 0 || j > 0) && SMALL_WORDS.has(bare)) return part;
          return part.replace(/[a-z]/, (c) => c.toUpperCase());
        })
        .join('-'),
    )
    .join('');
}

const isAllCapsHeading = (line: string) => {
  const letters = line.replace(/[^A-Za-z]/g, '');
  return (
    letters.length >= 6 &&
    letters === letters.toUpperCase() &&
    line.length <= 90 &&
    letters.length / line.replace(/\s/g, '').length >= 0.5
  );
};

/** "Target Market: rest" -> "**Target Market:** rest" so the label prints bold. */
const labelize = (s: string) => {
  const m = s.match(/^([A-Z][^:.!?]{1,40}):\s+(\S.*)$/);
  return m && !/^https?$/i.test(m[1]) ? `**${m[1]}:** ${m[2]}` : s;
};

/**
 * The business plan arrives as plain text with ALL-CAPS headings,
 * "Label:" subheadings and "•" bullets; turn it into markdown.
 */
export function businessPlanToMarkdown(plan: string, businessName = ''): string {
  const out: string[] = [];
  let first = true;
  for (const raw of plan.replace(/\r/g, '').split('\n')) {
    const line = raw.trim();
    if (!line) { out.push(''); continue; }
    if (/^[=_~-]{3,}$/.test(line)) { out.push('---'); continue; }
    if (first) {
      first = false;
      // The plan often opens with "BUSINESS PLAN: Name", which the PDF header already shows.
      if (/^business plan\b/i.test(line) && line.replace(/^business plan[:\s-]*/i, '').trim().toLowerCase() === businessName.trim().toLowerCase()) continue;
      if (/^business plan[:\s-]*$/i.test(line)) continue;
    }
    if (/^#{1,6}\s/.test(line) || line.startsWith('|')) { out.push(line); continue; }

    const bullet = raw.match(/^(\s*)(?:[•●▪◦o*+]|-(?=\s))\s+(.*)$/);
    if (bullet) {
      const nested = bullet[1].replace(/\t/g, '    ').length >= 2 || /^\s*[◦o]\s/.test(raw);
      out.push(`${nested ? '  ' : ''}- ${labelize(bullet[2].trim())}`);
      continue;
    }

    const stripped = line.replace(/^(?:\d+[.)]|[IVX]+\.|section\s+\d+[:.]?)\s*/i, '');
    if (isAllCapsHeading(stripped)) {
      // A light rule between major sections; none before the first.
      if (out.some((l) => l.startsWith('## '))) out.push('', '---');
      out.push('', `## ${titleCase(stripped.replace(/[:\s]+$/, ''))}`, '');
      continue;
    }

    const numbered = line.match(/^(\d+[.)])\s+(.*)$/);
    if (numbered) { out.push(`${numbered[1]} ${labelize(numbered[2])}`); continue; }

    if (/:$/.test(line) && line.length <= 70) {
      out.push('', `### ${line.replace(/:$/, '')}`);
      continue;
    }
    // Runs of "Label: value" lines stay together; other lines are paragraphs.
    const labelled = labelize(line);
    const prev = out[out.length - 1] ?? '';
    if (labelled.startsWith('**') && prev.startsWith('**')) out.push(labelled);
    else out.push('', labelled);
  }
  return out.join('\n');
}

export function generateBusinessPlanPDF(plan: string, businessName: string): jsPDF {
  const w = new PdfWriter();
  const name = asText(businessName) || 'Your Business';
  w.header(name, 'Business Plan');
  richMarkdown(w, businessPlanToMarkdown(typeof plan === 'string' ? plan : asText(plan), name));
  w.footer('Generated by PivotHub');
  return w.doc;
}
