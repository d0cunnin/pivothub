import type jsPDF from 'jspdf';
import { PdfWriter, asText } from '../pdfWriter';
import { note, rawText, renderAiText, wrappedHeader } from './toolReportBlocks';

/** Study It: biblical reference for a topic (AI markdown with ## sections). */
export function generateStudyItPDF(topic: string, content: string): jsPDF {
  const w = new PdfWriter();
  wrappedHeader(w, asText(topic) || 'Biblical Reference', 'Biblical Reference  ·  Reference-only material. No commentary or interpretation.');
  note(w, 'This file is not stored on our servers. Keep this download to save a copy.');
  renderAiText(w, rawText(content));
  w.footer('Generated by PivotHub Study It');
  return w.doc;
}
