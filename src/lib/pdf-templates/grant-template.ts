import type jsPDF from 'jspdf';
import { PdfWriter, asText } from '../pdfWriter';
import { reportHeader, renderAiText } from '../pdf-reports/reportBlocks';

interface GrantContactInfo {
  name: string;
  title: string;
  email: string;
  phone: string;
}

/** Numbered lines like "3. Program Design" with these names are treated as section headings. */
const PROPOSAL_HEADINGS =
  /^(executive summary|statement of need|need|problem|need\s*\/\s*problem|goals|objectives|program|project (design|description)|implementation|timeline|target population|community impact|evaluation|organizational (capacity|background)|budget|sustainability|conclusion|introduction|background|about|outcomes|key personnel|summary)/i;

export function generateGrantProposalPDF(
  proposal: string,
  loi: string,
  organizationName: string,
  projectTitle: string,
  contactInfo: GrantContactInfo
): jsPDF {
  const w = new PdfWriter();
  // Keep the raw text: the budget table and nested bullets are detected by
  // characters (box rules, bullets) that the PDF font cannot print.
  const raw = (v: unknown) => (typeof v === 'string' ? v : asText(v)).trim();
  const proposalText = raw(proposal);
  const loiText = raw(loi);

  const docType = proposalText ? 'Grant Proposal' : 'Letter of Intent';
  const project = asText(projectTitle);
  reportHeader(
    w,
    asText(organizationName) || docType,
    project ? `${project}  |  ${docType}` : docType,
  );

  const contactName = [asText(contactInfo?.name), asText(contactInfo?.title)].filter(Boolean).join(', ');
  if (contactName || contactInfo?.email || contactInfo?.phone) {
    w.section('Contact Information');
    w.facts([
      ['Contact', contactName],
      ['Email', asText(contactInfo?.email)],
      ['Phone', asText(contactInfo?.phone)],
    ]);
    w.y += 4;
  }

  if (proposalText) {
    w.section('Full Grant Proposal');
    renderAiText(w, proposalText, { numberedHeadings: PROPOSAL_HEADINGS, titleLineHeadings: true });
    w.y += 4;
  }

  if (loiText) {
    if (proposalText) {
      // A divider only when the letter can start on this page too.
      if (w.y + 50 <= w.pageHeight - w.margin - 5) w.divider();
      else w.ensureSpace(w.pageHeight);
    }
    w.section('Letter of Intent');
    renderAiText(w, loiText);
  }

  w.footer('Generated by PivotHub');

  // Validate PDF size before returning (max 5MB)
  const pdfSize = w.doc.output('arraybuffer').byteLength;
  const maxSize = 5 * 1024 * 1024;
  if (pdfSize > maxSize) {
    throw new Error('Generated PDF exceeds maximum size limit (5MB). Please reduce content length.');
  }

  return w.doc;
}
