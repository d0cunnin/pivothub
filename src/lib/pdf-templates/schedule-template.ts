import type jsPDF from 'jspdf';
import { PdfWriter, asText, toList, pdfSafe, ACCENT, BODY, HEADING, MUTED, DIVIDER, type RGB } from '../pdfWriter';
import { reportHeader, statTiles } from '../pdf-reports/reportBlocks';

interface TimeBlock {
  time: string;
  activity: string;
  category: 'work' | 'personal' | 'side-business' | 'rest';
}

interface DaySchedule {
  [key: string]: TimeBlock[];
}

interface ScheduleSummary {
  totalCommittedHours: number;
  totalAvailableHours: number;
  sideBusinessHours: number;
  personalTime: number;
  recommendations: string[];
}

interface ScheduleData {
  weeklySchedule: DaySchedule;
  summary: ScheduleSummary;
}

const CATEGORY_COLORS: Record<string, RGB> = {
  work: [59, 130, 246],
  personal: [16, 185, 129],
  'side-business': [139, 92, 246],
  business: [139, 92, 246],
  rest: [148, 163, 184],
  family: [236, 72, 153],
  fitness: [34, 197, 94],
  faith: [168, 85, 247],
  health: [239, 68, 68],
  study: [251, 146, 60],
  'personal-development': [14, 165, 233],
  creativity: [249, 115, 22],
  marriage: [244, 63, 94],
  children: [234, 179, 8],
};
const DEFAULT_COLOR: RGB = [203, 213, 225];

const DAYS = ['monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday', 'sunday'];

const categoryKey = (c: unknown) => asText(c).toLowerCase().trim().replace(/[\s_]+/g, '-');
const categoryLabel = (c: unknown) => {
  const key = categoryKey(c);
  if (!key) return '';
  const s = key.replace(/-/g, ' ');
  return s.charAt(0).toUpperCase() + s.slice(1);
};
const colorFor = (c: unknown): RGB => CATEGORY_COLORS[categoryKey(c)] ?? DEFAULT_COLOR;
const tint = (c: RGB, amount = 0.85): RGB => c.map((v) => Math.round(v + (255 - v) * amount)) as RGB;

/** Formats an hour count: 40 -> "40", 12.5 -> "12.5". */
const hours = (v: unknown) => {
  const n = typeof v === 'number' ? v : parseFloat(asText(v));
  if (!Number.isFinite(n)) return asText(v) || '-';
  return String(Math.round(n * 10) / 10);
};

/** Small colored category pill, right-aligned at `rightX`. Returns its width. */
function pill(w: PdfWriter, label: string, color: RGB, rightX: number, y: number) {
  w.setStyle(7.5, HEADING, 'bold');
  const text = pdfSafe(label);
  const width = w.doc.getTextWidth(text) + 5;
  w.doc.setFillColor(...tint(color));
  w.doc.roundedRect(rightX - width, y - 3.4, width, 4.8, 1.5, 1.5, 'F');
  w.doc.setTextColor(...color.map((v) => Math.round(v * 0.6)) as RGB);
  w.doc.text(text, rightX - width / 2, y, { align: 'center' });
  return width;
}

export function generateSchedulePDF(scheduleData: ScheduleData, userName: string = 'User'): jsPDF {
  const w = new PdfWriter();
  const name = asText(userName).trim();
  reportHeader(
    w,
    name && name !== 'User' ? `${name}'s Weekly Schedule` : 'Your Weekly Schedule',
    'Your personalized schedule, generated by PivotHub',
  );

  const summary: Partial<ScheduleSummary> = scheduleData?.summary ?? {};
  w.section('Your Week at a Glance');
  statTiles(w, [
    { value: hours(summary.totalCommittedHours), label: 'Committed hours', color: ACCENT },
    { value: hours(summary.totalAvailableHours), label: 'Available hours', color: HEADING },
    { value: hours(summary.sideBusinessHours), label: 'Side business hours', color: CATEGORY_COLORS.business },
    { value: hours(summary.personalTime), label: 'Personal time (hours)', color: CATEGORY_COLORS.personal },
  ]);

  // Legend of the categories that actually appear.
  const weekly = scheduleData?.weeklySchedule ?? {};
  const allBlocks = Object.values(weekly).flatMap((v) => (Array.isArray(v) ? v : []));
  const used = Array.from(new Set(allBlocks.map((b) => categoryKey(b?.category)).filter(Boolean)));
  if (used.length) {
    w.ensureSpace(10);
    w.setStyle(8.5, MUTED);
    let x = w.margin;
    used.forEach((key) => {
      const label = categoryLabel(key);
      const width = w.doc.getTextWidth(pdfSafe(label)) + 9;
      if (x + width > w.margin + w.contentWidth) { x = w.margin; w.y += 6; w.ensureSpace(6); }
      w.doc.setFillColor(...colorFor(key));
      w.doc.circle(x + 1.6, w.y - 1.1, 1.4, 'F');
      w.setStyle(8.5, MUTED);
      w.doc.text(pdfSafe(label), x + 4.5, w.y);
      x += width;
    });
    w.y += 10;
  }

  w.section('Weekly Schedule');
  const timeWidth = 36;
  const barX = w.margin;
  const timeX = w.margin + 4;
  const activityX = timeX + timeWidth;
  const rightX = w.margin + w.contentWidth;

  // Days the AI returned outside the usual keys are kept, after the week.
  const extraDays = Object.keys(weekly).filter((k) => !DAYS.includes(k.toLowerCase()));
  const dayKeys = [...DAYS, ...extraDays];

  dayKeys.forEach((day) => {
    const raw = weekly[day] ?? weekly[day.charAt(0).toUpperCase() + day.slice(1)];
    const blocks: TimeBlock[] = Array.isArray(raw) ? raw : [];
    const title = day.charAt(0).toUpperCase() + day.slice(1);

    // Keep the day heading with at least its first two blocks.
    w.ensureSpace(12 + Math.min(2, Math.max(1, blocks.length)) * 9);
    w.setStyle(12, ACCENT, 'bold');
    w.doc.text(pdfSafe(title), w.margin, w.y);
    w.y += 2.5;
    w.doc.setDrawColor(...DIVIDER);
    w.doc.setLineWidth(0.3);
    w.doc.line(w.margin, w.y, rightX, w.y);
    w.y += 5.5;

    if (!blocks.length) {
      w.text('No scheduled activities', { x: timeX, size: 9.5, color: MUTED, after: 5 });
      return;
    }

    blocks.forEach((block) => {
      const color = colorFor(block?.category);
      const label = categoryLabel(block?.category);
      w.setStyle(7.5, HEADING, 'bold');
      const pillWidth = label ? w.doc.getTextWidth(pdfSafe(label)) + 5 : 0;
      w.setStyle(9.5, HEADING, 'bold');
      const timeLines: string[] = w.doc.splitTextToSize(asText(block?.time), timeWidth - 3);
      w.setStyle(9.5, BODY);
      const actLines: string[] = w.doc.splitTextToSize(asText(block?.activity), rightX - activityX - pillWidth - 4);
      const rowLines = Math.max(timeLines.length, actLines.length, 1);
      const rowH = rowLines * 4.6 + 3.4;

      const before = w.doc.getNumberOfPages();
      w.ensureSpace(rowH);
      if (w.doc.getNumberOfPages() !== before) {
        w.setStyle(10, MUTED, 'bold');
        w.doc.text(pdfSafe(`${title} (continued)`), w.margin, w.y);
        w.y += 7;
      }

      const top = w.y - 3.6;
      w.doc.setFillColor(...tint(color, 0.9));
      w.doc.rect(barX, top, w.contentWidth, rowH - 1.2, 'F');
      w.doc.setFillColor(...color);
      w.doc.rect(barX, top, 1.4, rowH - 1.2, 'F');

      w.setStyle(9.5, HEADING, 'bold');
      timeLines.forEach((line, i) => w.doc.text(line, timeX, w.y + i * 4.6));
      w.setStyle(9.5, BODY);
      actLines.forEach((line, i) => w.doc.text(line, activityX, w.y + i * 4.6));
      if (label) pill(w, label, color, rightX - 2, w.y);
      w.y += rowH;
    });
    w.y += 5;
  });

  const recs = toList(summary.recommendations);
  if (recs.length) {
    w.y += 2;
    w.section('Recommendations', 'Small changes that make this schedule easier to keep');
    w.bullets(recs);
  }

  w.footer('This schedule is not stored in PivotHub. Please save this PDF for your records.');
  return w.doc;
}
